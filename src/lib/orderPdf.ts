import { jsPDF } from 'jspdf'
import { autoTable } from 'jspdf-autotable'
import { formatDate, formatMoneyPlain, formatNumber, orderNo } from './format'
import type { CatalogVariety } from './queries'
import type { OrderDetail } from './types'

const GREEN: [number, number, number] = [46, 125, 79]
const INK: [number, number, number] = [22, 33, 26]
const MUTED: [number, number, number] = [91, 107, 96]

export function buildOrderPdf(order: OrderDetail, varietyById: Map<string, CatalogVariety>): jsPDF {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' })
  const pageWidth = doc.internal.pageSize.getWidth()
  const margin = 14

  doc.setFillColor(...GREEN)
  doc.rect(0, 0, pageWidth, 28, 'F')
  doc.setTextColor(255, 255, 255)
  doc.setFont('times', 'bold')
  doc.setFontSize(22)
  doc.text('ASC FRUITS', margin, 17)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)
  doc.text('PURCHASE ORDER', pageWidth - margin, 12, { align: 'right' })
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(16)
  doc.text(orderNo(order.order_no), pageWidth - margin, 20, { align: 'right' })

  let y = 40
  doc.setTextColor(...MUTED)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(9)
  doc.text('VENDOR', margin, y)
  doc.text('ORDER DATE', pageWidth - margin, y, { align: 'right' })

  y += 6
  doc.setTextColor(...INK)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(13)
  doc.text(order.vendor?.name ?? '-', margin, y)
  doc.setFontSize(11)
  doc.text(formatDate(order.created_at), pageWidth - margin, y, { align: 'right' })

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)
  const vendorLines = [
    order.vendor?.contact_person,
    order.vendor?.phone && `Phone: ${order.vendor.phone}`,
    order.vendor?.address,
  ].filter(Boolean) as string[]
  for (const line of vendorLines) {
    y += 5
    doc.text(line, margin, y)
  }

  const items = order.order_items
  const totalKg = items.reduce((s, i) => s + Number(i.qty_kg), 0)
  const total = items.reduce((s, i) => s + Number(i.line_total), 0)

  autoTable(doc, {
    startY: y + 8,
    margin: { left: margin, right: margin },
    head: [['#', 'Fruit', 'Variety', 'Qty (kg)', 'Rate / kg', 'Amount']],
    body: items.map((item, idx) => {
      const v = varietyById.get(item.variety_id)
      return [
        String(idx + 1),
        v?.fruit.name ?? '',
        v?.name ?? 'Unknown',
        formatNumber(item.qty_kg),
        formatMoneyPlain(item.rate),
        formatMoneyPlain(item.line_total),
      ]
    }),
    foot: [['', '', 'Total', formatNumber(totalKg), '', formatMoneyPlain(total)]],
    theme: 'grid',
    styles: { fontSize: 10, cellPadding: 3, textColor: INK, lineColor: [220, 229, 220] },
    headStyles: { fillColor: GREEN, textColor: 255, fontStyle: 'bold' },
    footStyles: { fillColor: [227, 241, 232], textColor: INK, fontStyle: 'bold' },
    columnStyles: {
      0: { cellWidth: 10, halign: 'center' },
      3: { halign: 'right' },
      4: { halign: 'right' },
      5: { halign: 'right' },
    },
    didParseCell: (data) => {
      if (data.section !== 'body' && [3, 4, 5].includes(data.column.index)) {
        data.cell.styles.halign = 'right'
      }
    },
  })

  const finalY = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY
  let ny = finalY + 10
  if (order.notes) {
    doc.setTextColor(...MUTED)
    doc.setFontSize(9)
    doc.text('NOTES', margin, ny)
    doc.setTextColor(...INK)
    doc.setFontSize(10)
    const lines = doc.splitTextToSize(order.notes, pageWidth - margin * 2)
    doc.text(lines, margin, ny + 5)
    ny += 5 + lines.length * 5
  }

  doc.setTextColor(...MUTED)
  doc.setFontSize(8)
  doc.text(
    `Generated by ASC Fruits on ${new Date().toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' })}`,
    margin,
    doc.internal.pageSize.getHeight() - 10,
  )

  return doc
}

export function orderSummaryText(order: OrderDetail, varietyById: Map<string, CatalogVariety>): string {
  const lines = order.order_items.map((item) => {
    const v = varietyById.get(item.variety_id)
    return `- ${v?.name ?? 'Item'}: ${formatNumber(item.qty_kg)} kg @ ${formatMoneyPlain(item.rate)} = ${formatMoneyPlain(item.line_total)}`
  })
  const total = order.order_items.reduce((s, i) => s + Number(i.line_total), 0)
  return [
    `*ASC Fruits - Purchase Order ${orderNo(order.order_no)}*`,
    `Date: ${formatDate(order.created_at)}`,
    `Vendor: ${order.vendor?.name ?? ''}`,
    '',
    ...lines,
    '',
    `*Total: ${formatMoneyPlain(total)}*`,
    order.notes ? `\nNotes: ${order.notes}` : '',
  ]
    .join('\n')
    .trim()
}

export function whatsappNumber(raw: string | null | undefined): string {
  const digits = (raw ?? '').replace(/\D/g, '')
  if (digits.length === 10) return `91${digits}`
  return digits
}
